"""Write hdf_tables.h: the constant lookup tables of hdf.c.

Run again after changing a threshold: python gen_tables.py
"""
from pathlib import Path


def to_linear(s):
    return s / 12.92 if s <= 0.04045 else ((s + 0.055) / 1.055) ** 2.4


def to_srgb(l):
    l = min(max(l, 0.0), 1.0)
    return l * 12.92 if l <= 0.0031308 else 1.055 * l ** (1 / 2.4) - 0.055


def smoothstep(a, b, x):
    t = min(max((x - a) / (b - a), 0.0), 1.0)
    return t * t * (3 - 2 * t)


def table(ctype, name, values, per_line=16):
    rows = [", ".join(str(v) for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return f"static const {ctype} {name}[{len(values)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


# 8-bit code value -> linear light, 0..4095
lin = [round(to_linear(v / 255) * 4095) for v in range(256)]
# linear light 0..4095 -> 8-bit code value
srgb = [round(to_srgb(i / 4095) * 255) for i in range(4096)]
# brightest channel -> how much it spills (x256): starts at 40 % linear light,
# full at 95 %, and clipped values count up to 3x, as they were brighter than white
spill = [round(smoothstep(0.4, 0.95, to_linear(v / 255)) * (1 + 2 * smoothstep(0.85, 1.0, to_linear(v / 255))) * 256)
         for v in range(256)]
# luma -> halation mask (x255): the red ring shows around lights, not on them
halo_mask = [round((1 - smoothstep(0.3, 0.9, to_linear(v / 255))) * 255) for v in range(256)]
# (linear light >> 4) -> 2^20 / light, to take a share of the light without a division
recip = [round((1 << 20) / (i * 16 + 8)) for i in range(256)]

out = ["/* Generated by gen_tables.py. Do not edit. */\n#ifndef HDF_TABLES_H\n#define HDF_TABLES_H\n",
       table("u16", "LIN", lin), table("u8", "SRGB", srgb), table("u16", "SPILL", spill),
       table("u8", "HALO_MASK", halo_mask), table("u32", "RECIP", recip, 8), "#endif\n"]
Path(__file__).with_name("hdf_tables.h").write_text("\n".join(out))
