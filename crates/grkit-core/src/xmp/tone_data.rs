//! The response of each tone slider on a gray ramp, as fitted curves.
//!
//! Each curve maps a display value to the display value after the slider, at `KNOTS` even steps
//! from 0 to 1. The curves are fitted to renders of a synthetic gray ramp by the raw converter
//! that the presets are made for. A slider value between two measured amounts interpolates
//! between their curves, and 0 is the identity.
//!
//! Highlights and Shadows are different: the converter adapts them to each part of a picture,
//! so a gray ramp does not show what they do to a photograph. Their curves are the median
//! change of the luminance over renders of photographs, as display grays.

// A fitted value can be near a mathematical constant by chance.
#![allow(clippy::approx_constant)]

pub const KNOTS: usize = 33;

/// One tone slider: the measured amounts in rising order (0 left out) and the curve of each.
pub struct Slider {
    pub amounts: &'static [f64],
    pub curves: &'static [[f32; KNOTS]],
}

impl Slider {
    /// The display value after the slider at `amount`.
    pub fn eval(&self, amount: f64, x: f64) -> f64 {
        let x = x.clamp(0.0, 1.0);
        let at = |curve: Option<usize>| match curve {
            Some(index) => {
                let position = x * (KNOTS - 1) as f64;
                let low = (position as usize).min(KNOTS - 2);
                let t = position - low as f64;
                let knots = &self.curves[index];
                f64::from(knots[low]) * (1.0 - t) + f64::from(knots[low + 1]) * t
            }
            None => x,
        };
        // The neighbours of `amount` among the measured amounts and 0, which is the identity.
        let (mut below, mut above) = ((f64::NEG_INFINITY, None), (f64::INFINITY, None));
        let zero = std::iter::once((0.0, None));
        let measured = self.amounts.iter().enumerate().map(|(i, a)| (*a, Some(i)));
        for (value, curve) in measured.chain(zero) {
            if value <= amount && value > below.0 {
                below = (value, curve);
            }
            if value >= amount && value < above.0 {
                above = (value, curve);
            }
        }
        match (below.0.is_finite(), above.0.is_finite()) {
            (true, true) if above.0 > below.0 => {
                let t = (amount - below.0) / (above.0 - below.0);
                at(below.1) * (1.0 - t) + at(above.1) * t
            }
            (true, _) => at(below.1),
            _ => at(above.1),
        }
    }
}

